#!/usr/bin/env bash
# Regression: upgrading an existing operators table must add mfa_enabled and allow login.
# Exit 0 = green (login works after schema update). Exit 1 = red (MFA_ENABLED missing / login 500).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
H2="${HOME}/.m2/repository/com/h2database/h2/2.4.240/h2-2.4.240.jar"
APP="${ROOT}/dnscheck-service/target/quarkus-app"
WORKDIR="${TMPDIR:-/tmp}/mfa-schema-repro-$$"
PORT="${MFA_SCHEMA_REPRO_PORT:-18083}"

cleanup() {
  if [[ -f "${WORKDIR}/server.pid" ]]; then
    kill "$(cat "${WORKDIR}/server.pid")" 2>/dev/null || true
  fi
  pkill -f "quarkus.http.port=${PORT}" 2>/dev/null || true
}
trap cleanup EXIT

if [[ ! -f "${APP}/quarkus-run.jar" ]]; then
  echo "Build the service first: mvn -pl dnscheck-service -am package -DskipTests"
  exit 2
fi
if [[ ! -f "${H2}" ]]; then
  echo "H2 jar not found at ${H2}"
  exit 2
fi

rm -rf "${WORKDIR}"
mkdir -p "${WORKDIR}/data" "${WORKDIR}/zones" "${WORKDIR}/keys" "${WORKDIR}/app"
cp -R "${APP}/." "${WORKDIR}/app/"

# Pre-MFA schema with one operator row (bcrypt hash for "admin")
java -cp "${H2}" org.h2.tools.Shell \
  -url "jdbc:h2:file:${WORKDIR}/data/DNSCheck;DB_CLOSE_DELAY=-1" \
  -user dnscheck -password dnscheck -sql "
CREATE TABLE operators (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(255) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  enabled BOOLEAN NOT NULL
);
INSERT INTO operators(username, passwordHash, enabled)
VALUES('admin', '\$2a\$10\$DGIPXhFspxDHZsEbIERzmulpYCLJqefM8rx44SHnQoQuHJnht/SRW', TRUE);
" >/dev/null

(
  cd "${WORKDIR}/app"
  exec java \
    -Dquarkus.http.port="${PORT}" \
    -Dquarkus.datasource.jdbc.url="jdbc:h2:file:${WORKDIR}/data/DNSCheck;DB_CLOSE_DELAY=-1" \
    -Dquarkus.datasource.username=dnscheck \
    -Dquarkus.datasource.password=dnscheck \
    -Ddnscheck.zones.dir="${WORKDIR}/zones" \
    -Ddnscheck.keys.dir="${WORKDIR}/keys" \
    -Dquarkus.scheduler.enabled=false \
    -jar quarkus-run.jar
) >"${WORKDIR}/server.log" 2>&1 &
echo $! >"${WORKDIR}/server.pid"

code=""
for _ in $(seq 1 40); do
  code="$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:${PORT}/api/v1/health" || true)"
  if [[ "${code}" == "200" ]]; then
    break
  fi
  sleep 0.5
done
if [[ "${code}" != "200" ]]; then
  echo "Server failed to become healthy"
  tail -50 "${WORKDIR}/server.log" || true
  exit 3
fi

login="$(curl -s -w '\nHTTP %{http_code}' -X POST "http://127.0.0.1:${PORT}/api/v1/auth/login" \
  -H 'Content-Type: application/json' \
  -d '{"username":"admin","password":"admin"}' || true)"

if echo "${login}" | rg -q 'MFA_ENABLED|mfa_enabled'; then
  echo "RED: login still fails with missing MFA_ENABLED"
  echo "${login}"
  rg -n 'mfa_enabled|MFA_ENABLED|NULL not allowed' "${WORKDIR}/server.log" | head -20 || true
  exit 1
fi

if echo "${login}" | rg -q 'HTTP 200' && echo "${login}" | rg -q '"username"'; then
  echo "GREEN: login succeeded after schema upgrade"
  exit 0
fi

echo "UNKNOWN login outcome:"
echo "${login}"
tail -40 "${WORKDIR}/server.log" || true
exit 4
